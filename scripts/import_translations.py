#!/usr/bin/env python3
"""Turn checked translations from the Google Sheet into the readers' sentence list.

1. In the "Harari sentence translation" sheet, open the Translate tab and choose
   File → Download → Tab-separated values (.tsv).
2. Run:
       python scripts/import_translations.py ~/Downloads/"Harari sentence translation - Translate.tsv"
3. Commit docs/sentences.txt and texts/parallel/harari_english.tsv. Readers see new sentences on reload.

Only rows with Status = Checked are used. Each keeps its fixed ID (har_0001 ...), so the
sentence list can grow in any order without breaking recordings that already exist.
"""
import argparse
import csv
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEADER = """# Harari sentence list for the readers, generated by scripts/import_translations.py
# from the checked rows of the "Harari sentence translation" Google Sheet.
# Format: ID<TAB>Harari sentence. Edit the sheet, not this file, then re-run the script.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", help="Translate tab downloaded as .tsv")
    ap.add_argument("--include-translated", action="store_true", help="Also use rows marked Translated (not yet checked)")
    args = ap.parse_args()

    ok_status = {"checked"} | ({"translated"} if args.include_translated else set())
    rows = list(csv.DictReader(open(args.tsv, encoding="utf-8"), delimiter="\t"))
    col = next(c for c in rows[0] if c.lower().startswith("harari"))
    out, skipped = [], 0
    for r in rows:
        har = " ".join((r.get(col) or "").split())
        if not har or (r.get("Status") or "").strip().lower() not in ok_status:
            continue
        if re.search(r"\d", har):
            print(f"  {r['ID']}: contains digits — write numbers as words; skipped")
            skipped += 1
            continue
        out.append((r["ID"].strip(), har, r.get("English", "").strip()))

    with open(os.path.join(ROOT, "docs", "sentences.txt"), "w", encoding="utf-8") as f:
        f.write(HEADER)
        for i, har, _ in out:
            f.write(f"{i}\t{har}\n")
    os.makedirs(os.path.join(ROOT, "texts", "parallel"), exist_ok=True)
    with open(os.path.join(ROOT, "texts", "parallel", "harari_english.tsv"), "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter="\t")
        w.writerow(["id", "harari", "english"])
        w.writerows(out)
    print(f"Wrote {len(out)} sentences to docs/sentences.txt ({skipped} skipped).")


if __name__ == "__main__":
    main()
